use rufa_data::Sde;

macro_rules! attr_ids {
    ($($field:ident = $name:literal,)*) => {
        #[derive(Debug, Clone, Copy)]
        pub struct AttrIds {
            $(pub $field: i32,)*
        }

        impl AttrIds {
            /// Distinct ids with no SDE behind them, for unit tests of pure math.
            #[cfg(test)]
            pub fn placeholder() -> AttrIds {
                let mut next = 0;
                AttrIds {
                    $($field: { next += 1; next },)*
                }
            }

            pub fn resolve(sde: &Sde) -> Result<AttrIds, String> {
                Ok(AttrIds {
                    $($field: sde
                        .attribute_name_to_id($name)
                        .ok_or_else(|| format!("attribute {} missing from the SDE", $name))?,)*
                })
            }
        }
    };
}

